"""Plot SGD and ODE generalization errors from previously saved trajectories.

Load the results generated by SGD_ODE_comparison.py and save the original
SGD-versus-ODE generalization-error comparison without rerunning simulations.

Run from the repository root so relative paths resolve correctly.
"""

import os
import pickle
import numpy as np
import matplotlib.pyplot as plt
from matplotlib.colors import to_rgb

# Load previously saved SGD and ODE trajectories
save_dir = "results"
data_file = os.path.join(save_dir, "SGD_ODE_comparison.pkl")

with open(data_file, "rb") as f:
    results = pickle.load(f)

# Learning rates selected for the comparison figure
etas_to_plot = [0.01, 0.05, 0.1, 0.5, 1.0]

# Plot formatting used for the thesis figures
plt.rcParams.update({
    "font.size": 12,
    "axes.titlesize": 12,
    "axes.labelsize": 14,
    "xtick.labelsize": 16,
    "ytick.labelsize": 16,
    "legend.fontsize": 13,
    "axes.linewidth": 1.0,
    "xtick.direction": "in",
    "ytick.direction": "in",
    "xtick.top": True,
    "ytick.right": True,
    "xtick.major.size": 5,
    "ytick.minor.size": 3,
    "savefig.dpi": 300,
    "savefig.bbox": "tight",
})

# Darken the SGD curves to distinguish them from the corresponding ODE curves
def darken_color(color, factor=0.75):
    r, g, b = to_rgb(color)
    return (factor * r, factor * g, factor * b)

# Plot the SGD and ODE generalization-error trajectories
fig, ax = plt.subplots(figsize=(5.2, 3.8))

for eta in etas_to_plot:
    alpha = np.asarray(results[eta]["alpha"])
    gen_sgd = np.asarray(results[eta]["err_sgd"])
    gen_ode = np.asarray(results[eta]["err_th"])

    mask = alpha > 0
    alpha = alpha[mask]
    gen_sgd = gen_sgd[mask]
    gen_ode = gen_ode[mask]

    ode_line, = ax.loglog(
        alpha,
        gen_ode,
        label=rf"$\eta={eta}$",
        linewidth=1,
    )

    ax.loglog(
        alpha,
        gen_sgd,
        linestyle="--",
        color=darken_color(ode_line.get_color(), factor=0.75),
        linewidth=1.5,
    )

ax.set_xlabel(r"$\alpha$")
ax.set_ylabel(r"$\epsilon_g(\alpha)$")

# Reference power-law slope alpha^(-1/3)
alpha_ref1 = np.logspace(1.5, 4, 100)

# Anchor the reference line to the ODE curve for the selected learning rate
alpha_anchor = 1e1
eta_anchor = 0.1 if 0.1 in etas_to_plot else etas_to_plot[0]

alpha_data = np.asarray(results[eta_anchor]["alpha"])
gen_data = np.asarray(results[eta_anchor]["err_th"])

mask = (alpha_data > 0) & (gen_data > 0)
alpha_data = alpha_data[mask]
gen_data = gen_data[mask]

idx_anchor = np.argmin(np.abs(alpha_data - alpha_anchor))
y_anchor = gen_data[idx_anchor]

C_ref1 = y_anchor * alpha_data[idx_anchor]**(1/3)

ax.loglog(
    alpha_ref1,
    0.3 * C_ref1 * alpha_ref1**(-1/3),
    linestyle="--",
    color="grey",
    linewidth=1.4,
    label=r"$\alpha^{-1/3}$",
    zorder=20,
)

ax.set_xlim(2e-1, 1e4)
ax.grid(False)
ax.legend(frameon=False, loc="best", ncol=1)
fig.tight_layout()

# Save the comparison figure without requiring a plot window
figure_dir = "figures"
os.makedirs(figure_dir, exist_ok=True)
plot_path = os.path.join(figure_dir, "SGD_ODE_generalization_error.pdf")
fig.savefig(plot_path)
plt.close(fig)
print(f"Saved plot at: {plot_path}")
