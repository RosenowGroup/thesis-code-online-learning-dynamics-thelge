"""
Plot the theoretical order parameters rho, Q, and r from previously saved
SGD-versus-ODE comparison results.

The data are generated by SGD_ODE_comparison.ipynb and saved in
results/SGD_ODE_comparison.pkl. No ODE integration is performed here.
"""

import os
import pickle
import numpy as np
import matplotlib.pyplot as plt

# --- Load previously computed ODE results ---
save_dir = "results"
data_file = os.path.join(save_dir, "SGD_ODE_comparison.pkl")

with open(data_file, "rb") as f:
    results = pickle.load(f)

# --- Parameters for plotting ---
eta = 0.1                   # learning rate to plot

# ODE solution stored by SGD_ODE_comparison.ipynb
alpha = np.asarray(results[eta]["alpha"])
rho = np.asarray(results[eta]["rho_th"])
Q = np.asarray(results[eta]["Q_th"])
r_sol = 1 - rho / np.sqrt(Q)
alpha_max = np.max(alpha)

# --- Plot formatting ---
plt.rcParams.update({
    "font.size": 12,
    "axes.titlesize": 12,
    "axes.labelsize": 14,
    "xtick.labelsize": 16,
    "ytick.labelsize": 16,
    "legend.fontsize": 13,
    "axes.linewidth": 1.0,
    "xtick.direction": "in",
    "ytick.direction": "in",
    "xtick.top": True,
    "ytick.right": True,
    "xtick.major.size": 5,
    "ytick.major.size": 5,
    "xtick.minor.size": 3,
    "ytick.minor.size": 3,
    "savefig.dpi": 300,
    "savefig.bbox": "tight",
})

# --- Power-law fit on a selected log-log interval ---
def power_law_fit(alpha, y, alpha_min_fit, alpha_max_fit=None):
    """
    Fit y = C * alpha^p on a log-log scale over alpha_min_fit <= alpha <= alpha_max_fit.
    Returns C, p, fitted alpha grid, fitted y values.
    """

    if alpha_max_fit is None:
        alpha_max_fit = np.max(alpha)

    mask = (
        (alpha > 0) &
        (y > 0) &
        (alpha >= alpha_min_fit) &
        (alpha <= alpha_max_fit)
    )

    alpha_fit_data = alpha[mask]
    y_fit_data = y[mask]

    log_alpha = np.log(alpha_fit_data)
    log_y = np.log(y_fit_data)

    # log(y) = p log(alpha) + log(C)
    p, log_C = np.polyfit(log_alpha, log_y, deg=1)
    C = np.exp(log_C)

    alpha_fit_line = np.logspace(
        np.log10(alpha_fit_data.min()),
        np.log10(alpha_fit_data.max()),
        500
    )
    y_fit_line = C * alpha_fit_line**p

    return C, p, alpha_fit_line, y_fit_line

# The saved SGD/ODE comparison ends at alpha = 1e4, not 1e6.
# Fit the available late-time interval without changing the fitting method.
alpha_min_fit = 1e2
alpha_max_fit = alpha_max

# --- Fit rho and Q ---
C_rho, p_rho, alpha_rho_fit, rho_fit = power_law_fit(
    alpha, rho, alpha_min_fit, alpha_max_fit
)

C_Q, p_Q, alpha_Q_fit, Q_fit = power_law_fit(
    alpha, Q, alpha_min_fit, alpha_max_fit
)

print(f"rho fit: rho(alpha) ≈ {C_rho:.4g} * alpha^{p_rho:.4f}")
print(f"Q fit:   Q(alpha)   ≈ {C_Q:.4g} * alpha^{p_Q:.4f}")

# --- Plot rho and Q ---
fig, ax = plt.subplots(figsize=(5.2, 3.8))

ax.loglog(alpha, rho, label=r"$\rho(\alpha)$", linewidth=1.5)
ax.loglog(alpha, Q, label=r"$Q(\alpha)$", linewidth=1.5)

# --- Fitted power laws ---
ax.loglog(
    alpha_rho_fit,
    rho_fit,
    linestyle="--",
    color="black",
    linewidth=1.4,
    zorder=20,
    label=rf"$\rho \sim \alpha^{{{p_rho:.3f}}}$"
)

ax.loglog(
    alpha_Q_fit,
    Q_fit,
    linestyle="--",
    color="0.25",
    linewidth=1.4,
    zorder=20,
    label=rf"$Q \sim \alpha^{{{p_Q:.3f}}}$"
)

# --- Labels ---
ax.set_xlabel(r"$\alpha$")
ax.set_ylabel(r"$Q(\alpha), \rho(\alpha)$")

# --- Axes limits ---
ax.set_xlim(2e-1, alpha_max)

# Optional y-limits if needed
# ax.set_ylim(1e-2, 1e4)

# --- No grid ---
ax.grid(False)

# --- Legend ---
ax.legend(
    frameon=False,
    loc="best",
    ncol=1,
)

fig.tight_layout()

# --- Save figure ---
figure_dir = "figures"
os.makedirs(figure_dir, exist_ok=True)
plot_path = os.path.join(figure_dir, "ODE_rho_Q_loglog.pdf")
fig.savefig(plot_path)
plt.show()
plt.close(fig)
print(f"Saved plot at: {plot_path}")

# --- Fit r = 1 - rho / sqrt(Q) ---
C_r, p_r, alpha_r_fit, r_fit = power_law_fit(
    alpha, r_sol, alpha_min_fit, alpha_max_fit
)

print(f"r fit: r(alpha) ≈ {C_r:.4g} * alpha^{p_r:.4f}")

# --- Plot r ---
fig, ax = plt.subplots(figsize=(5.2, 3.8))

ax.loglog(
    alpha,
    r_sol,
    label=r"$r(\alpha)$",
    linewidth=1.5,
)

# --- Fitted power law ---
ax.loglog(
    alpha_r_fit,
    r_fit,
    linestyle="--",
    color="black",
    linewidth=1.4,
    zorder=20,
    label=rf"$r \sim \alpha^{{{p_r:.3f}}}$"
)

ax.set_xlabel(r"$\alpha$")
ax.set_ylabel(r"$r(\alpha)$")

ax.set_xlim(1e-1, alpha_max)

ax.grid(False)

ax.legend(
    frameon=False,
    loc="best",
)

fig.tight_layout()

# --- Save figure ---
plot_path = os.path.join(figure_dir, "r_alpha_ode.pdf")
fig.savefig(plot_path)
plt.show()
plt.close(fig)
print(f"Saved plot at: {plot_path}")
